def analyze_text(text):
    prediction = predict_proba([text])[0]

    biased_score = float(prediction[1]) * 100

    lime_explanation = explain_text(text)
    heatmap = build_attention_heatmap(text, lime_explanation)
    semantic_data = gemini_semantic_analysis(text)

    semantic_average = (
        semantic_data["loaded_language"] +
        semantic_data["identity_bias"] +
        semantic_data["emotional_framing"] +
        semantic_data["toxicity_risk"]
    ) / 4

    # smarter fusion
    overall_score = max(
        biased_score,
        semantic_average
    )

    # semantic override
    if semantic_data["bias_type"] != "NEUTRAL":
        overall_score += 10

    overall_score = min(100, round(overall_score))

    if overall_score >= 70:
        risk = "HIGH"
    elif overall_score >= 40:
        risk = "MEDIUM"
    else:
        risk = "LOW"

    return {
        "bias_detected": overall_score >= 50,
        "overall_score": overall_score,
        "risk_level": risk,

        "semantic_vectors": {
            "loaded_language": semantic_data["loaded_language"],
            "identity_bias": semantic_data["identity_bias"],
            "emotional_framing": semantic_data["emotional_framing"],
            "toxicity_risk": semantic_data["toxicity_risk"]
        },

        "model_interpretation": semantic_data["model_interpretation"],

        "attention_heatmap": heatmap,

        "sentence_vector": {
            "sentence": text,
            "bias_type": semantic_data["bias_type"]
        },

        "neutral_rewrite": semantic_data["neutral_rewrite"]
    }

